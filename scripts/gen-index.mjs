#!/usr/bin/env node
// Regenerates src/components/index.ts for every package from its Sq*.vue files.
// Usage: node scripts/gen-index.mjs
import { readdirSync, writeFileSync, existsSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { resolve } from 'node:path'

const root = fileURLToPath(new URL('..', import.meta.url))
for (const pkg of readdirSync(resolve(root, 'packages'))) {
  const dir = resolve(root, 'packages', pkg, 'src/components')
  if (!existsSync(dir)) continue
  const names = readdirSync(dir).filter((f) => /^Sq.*\.vue$/.test(f)).map((f) => f.slice(0, -4)).sort()
  const body = [
    '// Generated by scripts/gen-index.mjs — do not edit by hand.',
    ...names.map((n) => `export { default as ${n} } from './${n}.vue'`),
    '',
    `export const componentNames = ${JSON.stringify(names)} as const`,
    '',
  ].join('\n')
  writeFileSync(resolve(dir, 'index.ts'), body)
  console.log(`@squirkle/${pkg}: ${names.length} components`)
}

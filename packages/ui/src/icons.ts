export interface IconData {
  body: string
  width: number
  height: number
}

interface IconifyJSON {
  prefix: string
  icons: Record<string, { body: string; width?: number; height?: number }>
  aliases?: Record<string, { parent: string }>
  width?: number
  height?: number
}

const store = new Map<string, IconData | null>()
/** Bumped whenever icons arrive, so render functions re-read the store (works in Vue 2.7 and 3). */
export const iconStoreVersion = ref(0)

/** Registers an Iconify JSON collection (or a subset) for offline use. */
export function addCollection(json: IconifyJSON) {
  const w = json.width ?? 24
  const h = json.height ?? 24
  for (const [name, icon] of Object.entries(json.icons)) {
    store.set(`${json.prefix}:${name}`, { body: icon.body, width: icon.width ?? w, height: icon.height ?? h })
  }
  for (const [name, alias] of Object.entries(json.aliases ?? {})) {
    const parent = store.get(`${json.prefix}:${alias.parent}`)
    if (parent) store.set(`${json.prefix}:${name}`, parent)
  }
  iconStoreVersion.value++
}

/** Registers single icons: addIcons({ 'my:logo': { body: '<path d="…"/>', width: 24, height: 24 } }). */
export function addIcons(icons: Record<string, Partial<IconData> & { body: string }>) {
  for (const [name, d] of Object.entries(icons)) store.set(name, { body: d.body, width: d.width ?? 24, height: d.height ?? 24 })
  iconStoreVersion.value++
}

const queue = new Map<string, Set<string>>()
let flushScheduled = false

async function flush() {
  flushScheduled = false
  const api = config.icons.api
  const batches = Array.from(queue.entries())
  queue.clear()
  if (!api) return
  await Promise.all(
    batches.map(async ([prefix, names]) => {
      const list = Array.from(names)
      try {
        const res = await fetch(`${api}/${encodeURIComponent(prefix)}.json?icons=${list.map(encodeURIComponent).join(',')}`)
        if (!res.ok) throw new Error(String(res.status))
        const json = (await res.json()) as IconifyJSON
        if (json && json.icons) addCollection(json)
      } catch {
        // Network failure: leave unresolved icons empty rather than retrying in a loop.
      }
      for (const n of list) if (!store.has(`${prefix}:${n}`)) store.set(`${prefix}:${n}`, null)
      iconStoreVersion.value++
    }),
  )
}

/** Returns icon data; schedules a batched Iconify API request when missing. */
export function resolveIconify(name: string): IconData | null | undefined {
  void iconStoreVersion.value
  if (store.has(name)) return store.get(name)
  if (typeof window === 'undefined') return undefined
  const [prefix, icon] = name.split(':')
  if (!prefix || !icon) return null
  if (!queue.has(prefix)) queue.set(prefix, new Set())
  queue.get(prefix)!.add(icon)
  if (!flushScheduled) {
    flushScheduled = true
    setTimeout(flush, 0)
  }
  return undefined
}

export type ResolvedIcon = { kind: 'path'; d: string } | { kind: 'svg'; data: IconData } | { kind: 'pending' } | { kind: 'none' }

export function resolveIcon(icon: string | undefined): ResolvedIcon {
  if (!icon) return { kind: 'none' }
  let name = icon
  if (name.startsWith('$')) {
    const key = name.slice(1)
    name = config.icons.aliases[key] ?? key
  }
  if (/^[mM][\d\s.-]/.test(name)) return { kind: 'path', d: name }
  if (builtinIcons[name]) return { kind: 'path', d: builtinIcons[name] }
  if (name.includes(':')) {
    const data = resolveIconify(name)
    return data ? { kind: 'svg', data } : data === null ? { kind: 'none' } : { kind: 'pending' }
  }
  return { kind: 'none' }
}
